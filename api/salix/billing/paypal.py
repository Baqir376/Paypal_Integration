"""PayPal, through the APIMatic-generated Server SDK.

`paypal-server-sdk` is generated by APIMatic from PayPal's API definition -- every
file in the package says so -- and this module is the only place it is imported.
No hand-rolled HTTP reaches PayPal from Salix.

Three things about the shape of it:

**The SDK is synchronous.** Each call runs in a worker thread, because a slow
PayPal response must not stall every other request and the live pipeline stream
on the event loop.

**Capture is idempotent.** The request id is derived from the order, so a double
click, a reloaded return page and a retry after a dropped response are all the
same capture as far as PayPal is concerned.

**A wallet order is approved at `payer-action`.** An order created with
`payment_source.paypal` returns that link rather than `approve`, which is what
the older integration guides describe. Both are accepted.
"""

from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass
from typing import Any, Optional

from ..config import Settings
from .packs import Pack

log = logging.getLogger("salix.paypal")

#: Seconds before a PayPal call is abandoned.
TIMEOUT_S = 30

BRAND_NAME = "Salix"

#: The SDK's default is none, so one dropped connection fails a status check.
MAX_RETRIES = 2


class PayPalError(RuntimeError):
    """PayPal refused or could not be reached.

    `code` is PayPal's own issue name where there is one (`ORDER_NOT_APPROVED`,
    `INSTRUMENT_DECLINED`), so callers can branch on it rather than on wording.
    """

    def __init__(self, detail: str, *, code: str = "", retryable: bool = False):
        super().__init__(detail)
        self.detail = detail
        self.code = code
        self.retryable = retryable


@dataclass(frozen=True)
class OrderView:
    """The parts of a PayPal order Salix makes decisions on."""

    id: str
    status: str
    approve_url: str = ""
    capture_id: str = ""
    capture_status: str = ""
    amount: str = ""
    currency: str = ""


def _read(model: Any, name: str, default: Any = None) -> Any:
    """Read an optional field off an SDK model.

    A field absent from the response is either missing from the instance or set
    to the SDK's SKIP sentinel, which is a string and therefore truthy.
    """
    from paypalserversdk.api_helper import APIHelper

    value = getattr(model, name, default)
    return default if value is APIHelper.SKIP else value


def _view(order: Any) -> OrderView:
    approve_url = ""
    for link in _read(order, "links") or []:
        if _read(link, "rel") in ("payer-action", "approve"):
            approve_url = _read(link, "href") or ""
            break

    capture_id = capture_status = amount = currency = ""
    units = _read(order, "purchase_units") or []
    if units:
        payments = _read(units[0], "payments")
        captures = (_read(payments, "captures") or []) if payments else []
        if captures:
            capture = captures[0]
            capture_id = _read(capture, "id") or ""
            capture_status = _read(capture, "status") or ""
            money = _read(capture, "amount")
            if money:
                amount = _read(money, "value") or ""
                currency = _read(money, "currency_code") or ""

    return OrderView(
        id=_read(order, "id") or "",
        status=_read(order, "status") or "",
        approve_url=approve_url,
        capture_id=capture_id,
        capture_status=capture_status,
        amount=amount,
        currency=currency,
    )


def _translate(exc: Exception) -> PayPalError:
    """Turn whatever the SDK raised into one error type."""
    from paypalserversdk.exceptions.api_exception import ApiException

    if isinstance(exc, ApiException):
        details = getattr(exc, "details", None) or []
        code = (_read(details[0], "issue") if details else None) or getattr(exc, "name", "") or ""
        debug_id = getattr(exc, "debug_id", "") or ""
        # The debug id is what PayPal support asks for, and the only thing that
        # ties this log line to anything on their side.
        log.warning(
            "paypal refused: status=%s code=%s debug_id=%s",
            exc.response_code, code, debug_id,
        )
        return PayPalError(
            f"PayPal refused the request ({code or exc.response_code}).",
            code=code,
            retryable=exc.response_code >= 500,
        )
    log.warning("paypal unreachable: %s", type(exc).__name__)
    return PayPalError("PayPal could not be reached.", retryable=True)


class PayPalGateway:
    def __init__(self, settings: Settings, *, http_client: Any = None):
        from paypalserversdk.configuration import Environment
        from paypalserversdk.http.auth.o_auth_2 import ClientCredentialsAuthCredentials
        from paypalserversdk.paypal_serversdk_client import PaypalServersdkClient

        self.environment = settings.paypal_mode
        self._orders = PaypalServersdkClient(
            client_credentials_auth_credentials=ClientCredentialsAuthCredentials(
                o_auth_client_id=settings.paypal_client_id,
                o_auth_client_secret=settings.paypal_client_secret,
            ),
            environment=(
                Environment.PRODUCTION
                if settings.paypal_mode == "production"
                else Environment.SANDBOX
            ),
            timeout=TIMEOUT_S,
            # GET and PUT only, by the SDK's default. A capture is a POST, and is made
            # safe to repeat by its request id rather than by retrying here.
            max_retries=MAX_RETRIES,
            http_client_instance=http_client,
        ).orders

    async def _call(self, method: Any, options: dict[str, Any]) -> OrderView:
        try:
            response = await asyncio.to_thread(method, options)
        except Exception as exc:  # noqa: BLE001
            raise _translate(exc) from exc
        # The SDK reports some failures on the result instead of raising. Read as an
        # order, one of those looks like an order with nothing on it, which turned a
        # failed capture into "not completed yet".
        if response.is_error():
            status = response.status_code
            log.warning("paypal answered %s with an error result", status)
            raise PayPalError(f"PayPal refused the request ({status}).", retryable=status >= 500)
        return _view(response.body)

    async def create_order(
        self,
        pack: Pack,
        *,
        org_id: str,
        request_id: str,
        return_url: str,
        cancel_url: str,
    ) -> OrderView:
        from paypalserversdk.models.amount_with_breakdown import AmountWithBreakdown
        from paypalserversdk.models.checkout_payment_intent import CheckoutPaymentIntent
        from paypalserversdk.models.order_request import OrderRequest
        from paypalserversdk.models.payment_source import PaymentSource
        from paypalserversdk.models.paypal_experience_user_action import (
            PaypalExperienceUserAction,
        )
        from paypalserversdk.models.paypal_wallet import PaypalWallet
        from paypalserversdk.models.paypal_wallet_context_shipping_preference import (
            PaypalWalletContextShippingPreference,
        )
        from paypalserversdk.models.paypal_wallet_experience_context import (
            PaypalWalletExperienceContext,
        )
        from paypalserversdk.models.purchase_unit_request import PurchaseUnitRequest

        body = OrderRequest(
            intent=CheckoutPaymentIntent.CAPTURE,
            purchase_units=[
                PurchaseUnitRequest(
                    reference_id=pack.id,
                    custom_id=org_id,
                    description=f"{BRAND_NAME}: {pack.credits} call analysis credits",
                    amount=AmountWithBreakdown(
                        currency_code=pack.currency, value=pack.price
                    ),
                )
            ],
            payment_source=PaymentSource(
                paypal=PaypalWallet(
                    experience_context=PaypalWalletExperienceContext(
                        brand_name=BRAND_NAME,
                        # Credits are not shipped anywhere, and asking for an
                        # address would only add a step to the checkout.
                        shipping_preference=PaypalWalletContextShippingPreference.NO_SHIPPING,
                        user_action=PaypalExperienceUserAction.PAY_NOW,
                        return_url=return_url,
                        cancel_url=cancel_url,
                    )
                )
            ),
        )
        view = await self._call(
            self._orders.create_order,
            {
                "body": body,
                "paypal_request_id": request_id,
                "prefer": "return=representation",
            },
        )
        if not view.id or not view.approve_url:
            raise PayPalError("PayPal returned an order with no way to approve it.")
        return view

    async def capture_order(self, order_id: str) -> OrderView:
        try:
            return await self._call(
                self._orders.capture_order,
                {
                    "id": order_id,
                    "paypal_request_id": f"salix-capture-{order_id}",
                    "prefer": "return=representation",
                },
            )
        except PayPalError as exc:
            # Already taken, by an earlier attempt whose response was lost. Not
            # a failure: the money moved, so read what happened.
            if exc.code == "ORDER_ALREADY_CAPTURED":
                return await self.get_order(order_id)
            raise

    async def get_order(self, order_id: str) -> OrderView:
        return await self._call(self._orders.get_order, {"id": order_id})


_gateway: Optional[PayPalGateway] = None


def get_gateway(settings: Settings) -> PayPalGateway:
    """One client per process, so its OAuth token is reused between requests."""
    global _gateway
    if not settings.paypal_configured:
        raise PayPalError("PayPal is not configured on this server.")
    if _gateway is None:
        if settings.paypal_simulated:
            from . import simulator

            _gateway = PayPalGateway(
                settings.model_copy(
                    update={"paypal_client_id": "simulated", "paypal_client_secret": "simulated"}
                ),
                http_client=simulator.http_client(settings),
            )
        else:
            _gateway = PayPalGateway(settings)
    return _gateway


def reset_gateway(gateway: Optional[PayPalGateway] = None) -> None:
    global _gateway
    _gateway = gateway
